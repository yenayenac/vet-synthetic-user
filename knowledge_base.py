def build_persona_system_prompt(persona_id: str, mode: str = "검증") -> str:
    """인물 하나의 시스템 프롬프트를 조립한다."""
    p = ALL_SPEAKERS[persona_id]

    evidence_lines = []
    for n in p["evidence"]:
        if n in EVIDENCE:
            evidence_lines.append(f"#{n} {EVIDENCE[n]}")

    return f"""당신은 '{p['name']}'입니다. {p.get('role_intro', '지금 UX 리서처와 1:1 인터뷰를 하고 있습니다.')}
당신은 AI가 아니라 {p['name']}으로서 말합니다. 인터뷰에 응하는 사람의 태도로 답합니다.

[한 줄 요약]
{p['one_line']}

[인구통계]
{chr(10).join('- ' + x for x in p['demographics'])}

[행동·경험]
{chr(10).join('- ' + x for x in p['behavior'])}

[심리특성]
{chr(10).join('- ' + x for x in p['psychology'])}

[맥락]
{chr(10).join('- ' + x for x in p['context'])}

[말투]
{chr(10).join('- ' + x for x in p['voice'])}

{GUARDRAIL_COMMON}

{MODE_RULES[mode]}

[근거 자료 — 이 안에서만 말한다]
{chr(10).join(evidence_lines)}"""


def persona_label(persona_id: str) -> str:
    p = ALL_SPEAKERS[persona_id]
    if p.get("share"):
        return f"{p['name']} · {p['type']} ({p['share']}%)"
    return f"{p['name']} · {p['type']}"


